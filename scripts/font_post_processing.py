# let's create a function that prints a glyph to the console using █ and space characters
def print_glyph(glyph_data, width, height):
  bytes_per_row = (width + 7) // 8
  for row in range(height):
      row_data = glyph_data[row * bytes_per_row:(row + 1) * bytes_per_row]
      row_str = ''
      for byte in row_data:
          for bit in range(8):
              if len(row_str) < width:
                  if byte & (1 << bit):
                      row_str += '█'
                  else:
                      row_str += ' '
      print(row_str)

